-- SmartRoute initial schema
-- Derived 1:1 from the JPA entity mappings (106 source files audited).
-- No data is inserted: real university transport data must come from the
-- genuine workbook import (TransportWorkbookImporter).

-- ============================================================
-- Core identity
-- ============================================================
CREATE TABLE users (
    id                      BINARY(16)     NOT NULL,
    name                    VARCHAR(100)   NOT NULL,
    email                   VARCHAR(255)   NOT NULL,
    password_hash           VARCHAR(255)   NOT NULL,
    role                    VARCHAR(20)    NOT NULL,
    active                  TINYINT(1)     NOT NULL DEFAULT 1,
    email_verified          TINYINT(1)     NOT NULL DEFAULT 0,
    last_login_at           DATETIME(6)    NULL,
    failed_login_attempts   INT            NULL,
    locked_until            DATETIME(6)    NULL,
    password_changed_at     DATETIME(6)    NULL,
    created_at              DATETIME(6)    NOT NULL,
    updated_at              DATETIME(6)    NOT NULL,
    version                 BIGINT         NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    KEY idx_users_email (email),
    KEY idx_users_role (role),
    KEY idx_users_active (active),
    KEY idx_users_created_at (created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE otps (
    id                      BINARY(16)     NOT NULL,
    email                   VARCHAR(255)   NOT NULL,
    type                    VARCHAR(30)    NOT NULL,
    otp_hash                VARCHAR(255)   NOT NULL,
    expires_at              DATETIME(6)    NOT NULL,
    used                    TINYINT(1)     NOT NULL DEFAULT 0,
    used_at                 DATETIME(6)    NULL,
    attempt_count           INT            NOT NULL,
    max_attempts            INT            NOT NULL,
    resend_cooldown_until   DATETIME(6)    NULL,
    created_at              DATETIME(6)    NOT NULL,
    updated_at              DATETIME(6)    NOT NULL,
    version                 BIGINT         NULL,
    PRIMARY KEY (id),
    KEY idx_otps_email_type (email, type),
    KEY idx_otps_expires_at (expires_at),
    KEY idx_otps_used (used),
    KEY idx_otps_created_at (created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

-- ============================================================
-- Transport network (populated only by the genuine workbook import)
-- ============================================================
CREATE TABLE zones (
    id             BINARY(16)    NOT NULL,
    name           VARCHAR(100)  NOT NULL,
    code           VARCHAR(20)   NOT NULL,
    description    VARCHAR(255)  NULL,
    display_order  INT           NULL,
    active         TINYINT(1)    NOT NULL DEFAULT 1,
    created_at     DATETIME(6)   NOT NULL,
    updated_at     DATETIME(6)   NOT NULL,
    version        BIGINT        NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_zones_name UNIQUE (name),
    CONSTRAINT uk_zones_code UNIQUE (code)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE buses (
    id                      BINARY(16)    NOT NULL,
    registration_number     VARCHAR(20)   NOT NULL,
    bus_number              VARCHAR(50)   NULL,
    capacity                INT           NOT NULL DEFAULT 50,
    model                   VARCHAR(100)  NULL,
    fuel_type               VARCHAR(50)   NULL,
    manufacture_year        INT           NULL,
    driver_name             VARCHAR(100)  NULL,
    driver_phone            VARCHAR(20)   NULL,
    conductor_name          VARCHAR(100)  NULL,
    conductor_phone         VARCHAR(20)   NULL,
    active                  TINYINT(1)    NOT NULL DEFAULT 1,
    gps_device_id           VARCHAR(100)  NULL,
    last_location_lat       DOUBLE        NULL,
    last_location_lng       DOUBLE        NULL,
    last_location_at       DATETIME(6)   NULL,
    current_students_count  INT           NOT NULL DEFAULT 0,
    created_at              DATETIME(6)   NOT NULL,
    updated_at              DATETIME(6)   NOT NULL,
    version                 BIGINT        NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_buses_registration UNIQUE (registration_number)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE routes (
    id                          BINARY(16)      NOT NULL,
    zone_id                     BINARY(16)      NOT NULL,
    route_code                  VARCHAR(20)     NOT NULL,
    route_name                  VARCHAR(100)    NULL,
    direction                   VARCHAR(20)     NOT NULL,
    starting_point              VARCHAR(255)    NULL,
    starting_time               DATETIME(6)    NULL,
    ending_point                VARCHAR(255)    NULL,
    ending_time                 DATETIME(6)    NULL,
    description                 VARCHAR(500)    NULL,
    distance_km                 DOUBLE          NULL,
    estimated_duration_minutes  INT             NULL,
    active                      TINYINT(1)      NOT NULL DEFAULT 1,
    display_order               INT             NULL DEFAULT 0,
    fee_amount                  DECIMAL(10,2)   NULL,
    bus_id                      BINARY(16)      NULL,
    created_at                  DATETIME(6)     NOT NULL,
    updated_at                  DATETIME(6)     NOT NULL,
    version                     BIGINT          NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_routes_zone_code_direction UNIQUE (zone_id, route_code, direction),
    CONSTRAINT fk_routes_zone FOREIGN KEY (zone_id) REFERENCES zones (id),
    CONSTRAINT fk_routes_bus FOREIGN KEY (bus_id) REFERENCES buses (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE boarding_points (
    id                     BINARY(16)       NOT NULL,
    route_id               BINARY(16)       NOT NULL,
    stop_name              VARCHAR(100)     NOT NULL,
    stop_description       VARCHAR(255)     NULL,
    stop_order             INT              NOT NULL,
    stop_time              DATETIME(6)     NULL,
    latitude               DECIMAL(10,7)    NULL,
    longitude              DECIMAL(10,7)    NULL,
    landmark               VARCHAR(100)     NULL,
    active                 TINYINT(1)       NOT NULL DEFAULT 1,
    wheelchair_accessible  TINYINT(1)       NOT NULL DEFAULT 0,
    shelter_available      TINYINT(1)       NOT NULL DEFAULT 0,
    created_at             DATETIME(6)     NOT NULL,
    updated_at             DATETIME(6)     NOT NULL,
    version                BIGINT           NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_boarding_points_route_stop_order UNIQUE (route_id, stop_order),
    CONSTRAINT fk_boarding_points_route FOREIGN KEY (route_id) REFERENCES routes (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

